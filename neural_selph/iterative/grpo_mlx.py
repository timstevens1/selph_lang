def train_grpo(args):
    print(f"MLX backend on {mx.default_device()}")

    tokenizer = build_default_tokenizer()
    kb = json.loads((DATA_DIR / "geo_kb.json").read_text())
    data = json.loads((DATA_DIR / "geo_train.json").read_text())
    print(f"Tasks: {len(data)}, Vocab: {tokenizer.vocab_size}")

    # Train/eval split
    random.seed(42)
    indices = list(range(len(data)))
    random.shuffle(indices)
    split = int(0.9 * len(indices))
    train_tasks = [data[i] for i in indices[:split]]
    eval_tasks = [data[i] for i in indices[split:]]
    # Subsample eval for speed
    eval_subset = eval_tasks[:min(100, len(eval_tasks))]

    # Build policy model and load SFT weights
    model = build_model(tokenizer.vocab_size, args)
    sft_path = args.sft_path
    weights = dict(mx.load(sft_path))
    model.load_weights(list(weights.items()))
    mx.eval(model.parameters())

    n_params = sum(p.size for _, p in tree_flatten(model.parameters()))
    print(f"Policy model: {n_params:,} params, loaded from {sft_path}")

    # Build frozen reference model
    ref_model = build_model(tokenizer.vocab_size, args)
    ref_model.load_weights(list(weights.items()))
    mx.eval(ref_model.parameters())
    ref_model.eval()  # always in eval mode

    # Optimizer
    optimizer = optim.Adam(learning_rate=args.lr)

    # Baseline eval
    print("\n--- SFT Baseline (no queries) ---")
    baseline = quick_eval(model, tokenizer, kb, eval_subset, use_queries=False)
    total_ok = sum(v["ok"] for v in baseline.values())
    total_n = sum(v["total"] for v in baseline.values())
    print(f"  Overall: {total_ok}/{total_n} ({total_ok/max(total_n,1)*100:.1f}%)")
    for d in sorted(baseline):
        r = baseline[d]
        print(f"  Depth {d}: {r['ok']}/{r['total']} ({r['ok']/max(r['total'],1)*100:.1f}%)")

    # GRPO training loop
    print(f"\n--- GRPO Training ---")
    print(f"  group_size={args.group_size}, temperature={args.temperature}")
    print(f"  clip_eps={args.clip_eps}, kl_coef={args.kl_coef}, lr={args.lr}")
    print(f"  batch_size={args.batch_size}, epochs={args.epochs}")

    best_acc = total_ok / max(total_n, 1)
    t0 = time.time()

    for epoch in range(args.epochs):
        model.train()
        epoch_loss = 0.0
        epoch_batches = 0
        epoch_trajs = 0
        epoch_correct = 0
        epoch_queries = 0

        # Shuffle tasks each epoch
        random.shuffle(train_tasks)

        for batch_start in range(0, min(len(train_tasks), args.tasks_per_epoch), args.batch_size):
            batch_end = min(batch_start + args.batch_size, len(train_tasks))
            batch_tasks = train_tasks[batch_start:batch_end]

            # Phase 1: Collect trajectories (no grad)
            model.eval()
            all_trajectories = []
            all_advantages = []

            for task in batch_tasks:
                group_trajs = []
                for g in range(args.group_size):
                    traj = collect_trajectory(
                        model, tokenizer, kb, task,
                        temperature=args.temperature,
                        max_steps=args.max_steps,
                    )
                    traj.task_idx = id(task)
                    group_trajs.append(traj)
                    epoch_trajs += 1
                    if traj.correct:
                        epoch_correct += 1
                    if traj.used_query:
                        epoch_queries += 1

                # Group-normalize advantages
                rewards = [t.reward for t in group_trajs]
                mean_r = sum(rewards) / len(rewards)
                std_r = math.sqrt(sum((r - mean_r) ** 2 for r in rewards) / len(rewards))
                if std_r < 1e-8:
                    # All same reward — zero advantage
                    advs = [0.0] * len(rewards)
                else:
                    advs = [(r - mean_r) / (std_r + 1e-8) for r in rewards]

                all_trajectories.extend(group_trajs)
                all_advantages.extend(advs)

            # Skip if no meaningful advantages
            if all(abs(a) < 1e-8 for a in all_advantages):
                continue

            # Phase 2: Compute GRPO loss and update
            model.train()
            loss_fn = lambda m: grpo_loss(
                m, ref_model, all_trajectories, all_advantages,
                clip_eps=args.clip_eps, kl_coef=args.kl_coef,
            )
            loss, grads = nn.value_and_grad(model, loss_fn)(model)
            grads, _ = optim.clip_grad_norm(grads, max_norm=1.0)
            optimizer.update(model, grads)
            mx.eval(model.parameters(), optimizer.state, loss)

            batch_loss = float(loss.item())
            if not math.isnan(batch_loss):
                epoch_loss += batch_loss
                epoch_batches += 1

        # Epoch summary
        avg_loss = epoch_loss / max(epoch_batches, 1)
        traj_acc = epoch_correct / max(epoch_trajs, 1)
        elapsed = time.time() - t0

        # Eval periodically
        if (epoch + 1) % args.eval_every == 0 or epoch == args.epochs - 1:
            model.eval()
            # Eval with queries
            res_q = quick_eval(model, tokenizer, kb, eval_subset, use_queries=True)
            ok_q = sum(v["ok"] for v in res_q.values())
            n_q = sum(v["total"] for v in res_q.values())
            acc_q = ok_q / max(n_q, 1)

            # Eval without queries
            res_nq = quick_eval(model, tokenizer, kb, eval_subset, use_queries=False)
            ok_nq = sum(v["ok"] for v in res_nq.values())
            acc_nq = ok_nq / max(n_q, 1)

            marker = ""
            if acc_q > best_acc:
                best_acc = acc_q
                save_path = DATA_DIR / "iterative_model_grpo.npz"
                flat = dict(tree_flatten(model.parameters()))
                mx.savez(str(save_path), **flat)
                marker = " *saved*"

            print(f"epoch {epoch+1:3d}/{args.epochs}  loss={avg_loss:.4f}  "
                  f"traj_acc={traj_acc:.2f}  queries={epoch_queries}/{epoch_trajs}  "
                  f"eval_q={ok_q}/{n_q}({acc_q*100:.1f}%)  "
                  f"eval_nq={ok_nq}/{n_q}({acc_nq*100:.1f}%)  "
                  f"elapsed={elapsed:.0f}s{marker}")

            # Per-depth breakdown
            for d in sorted(res_q):
                rq = res_q[d]
                rnq = res_nq.get(d, {"ok": 0, "total": 0})
                print(f"  d={d}: q={rq['ok']}/{rq['total']}  nq={rnq['ok']}/{rnq['total']}")
        else:
            print(f"epoch {epoch+1:3d}/{args.epochs}  loss={avg_loss:.4f}  "
                  f"traj_acc={traj_acc:.2f}  queries={epoch_queries}/{epoch_trajs}  "
                  f"elapsed={elapsed:.0f}s")

    print(f"\nBest eval accuracy (with queries): {best_acc*100:.1f}%")
    print(f"Total time: {time.time() - t0:.0f}s")


def main():
    parser = argparse.ArgumentParser(description="GRPO training for query channel")
    # Model architecture (must match SFT checkpoint)
    parser.add_argument("--dim", type=int, default=96)
    parser.add_argument("--feat-dim", type=int, default=48)
    parser.add_argument("--state-dim", type=int, default=8)
    parser.add_argument("--num-layers", type=int, default=3)
    parser.add_argument("--num-scales", type=int, default=3)
    parser.add_argument("--shifts", type=int, nargs="+", default=[0, 1, 2, 4])
    parser.add_argument("--a-log-mults", type=float, nargs="+", default=[2.0, 1.0, 0.3])
    parser.add_argument("--mlp-mult", type=int, default=2)
    parser.add_argument("--weight-tie-layers", type=int, default=0)
    # GRPO hyperparameters
    parser.add_argument("--sft-path", default=str(DATA_DIR / "iterative_model_mlx.npz"))
    parser.add_argument("--group-size", type=int, default=4)
    parser.add_argument("--temperature", type=float, default=0.7)
    parser.add_argument("--clip-eps", type=float, default=0.2)
    parser.add_argument("--kl-coef", type=float, default=0.05)
    parser.add_argument("--lr", type=float, default=1e-5)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--tasks-per-epoch", type=int, default=256)
    parser.add_argument("--epochs", type=int, default=50)
    parser.add_argument("--max-steps", type=int, default=5)
    parser.add_argument("--eval-every", type=int, default=5)
    args = parser.parse_args()
    train_grpo(args)


if __name__ == "__main__":
    main()
