"""GRPO (Group Relative Policy Optimization) for the query channel.

Trains the iterative refinement model to discover when and what to query
via outcome-based RL. Teacher-forced query training adds only +0.3pp;
GRPO lets the model learn query strategies from trajectory rewards.

Usage:
    python3 -m neural_selph.iterative.grpo_mlx --epochs 50 --dim 96 --feat-dim 48 --num-layers 3
"""
