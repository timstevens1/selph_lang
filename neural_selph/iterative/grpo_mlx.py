# ============================================================================
# Data structures
# ============================================================================

@dataclass
class StepData:
    """One refinement step's generation data."""
    context_ids: list[int]    # input context (not generated by model)
    gen_ids: list[int]        # all tokens after context (model + injected)
    gen_mask: list[bool]      # True = model-generated, False = injected
    old_log_probs: list[float]  # log-prob at generation time (model-generated only)


@dataclass
class Trajectory:
    """A full multi-step refinement trajectory."""
    task_idx: int
    correct: bool
    num_steps: int
    reward: float
    steps: list[StepData] = field(default_factory=list)
    used_query: bool = False


# ============================================================================
# Trajectory collection
# ============================================================================

def generate_with_log_probs(
    model: MultiScaleFFNLM,
    input_ids: mx.array,
    tokenizer: SexprTokenizer,
    kb: dict,
    temperature: float = 0.7,
    max_new_tokens: int = 60,
    max_queries: int = 3,
) -> tuple[list[int], list[bool], list[float], bool]:
    """Autoregressive generation with sampling, log-prob collection, and query support.

    Returns:
        gen_ids: all generated/injected token IDs
        gen_mask: True for model-generated tokens, False for injected
        log_probs: log-prob for each model-generated token (len = sum(gen_mask))
        used_query: whether any <query> was emitted
    """
    ids = input_ids[None, :]  # (1, seq_len)
    gen_ids = []
    gen_mask = []
    log_probs = []
    used_query = False

    query_start_id = tokenizer.token_to_id.get("<query>")
    query_end_id = tokenizer.token_to_id.get("</query>")

    for _ in range(max_new_tokens):
        x = model(ids)
        logits = x[:, -1, :] @ model.tok_emb.weight.astype(x.dtype).T
        logits = model.softcap(logits).astype(mx.float32)

        # Sample
        probs = mx.softmax(logits / temperature, axis=-1)
        log_p = mx.log(probs + 1e-10)
        next_id = int(mx.random.categorical(log_p).item())
        token_log_prob = float(log_p[0, next_id].item())
        mx.eval(log_p)
        del x, logits, probs

        gen_ids.append(next_id)
        gen_mask.append(True)
        log_probs.append(token_log_prob)

        if next_id == tokenizer.eos_id:
            break

        ids = mx.concatenate([ids, mx.array([[next_id]], dtype=mx.int32)], axis=1)

        # Query interception
        if next_id == query_start_id and max_queries > 0:
            used_query = True
            query_token_ids = []
            for _ in range(20):
                x = model(ids)
                logits = x[:, -1, :] @ model.tok_emb.weight.astype(x.dtype).T
                logits = model.softcap(logits).astype(mx.float32)
                probs = mx.softmax(logits / temperature, axis=-1)
                log_p = mx.log(probs + 1e-10)
                qid = int(mx.random.categorical(log_p).item())
                q_log_prob = float(log_p[0, qid].item())
                mx.eval(log_p)
                del x, logits, probs

                gen_ids.append(qid)
                gen_mask.append(True)  # query body is model-generated
                log_probs.append(q_log_prob)

                ids = mx.concatenate([ids, mx.array([[qid]], dtype=mx.int32)], axis=1)

                if qid == query_end_id:
                    break
                query_token_ids.append(qid)

            # Evaluate query against KB
            query_sexpr = tokenizer.decode_to_sexpr(query_token_ids)
            q_result = ""
            if query_sexpr and "_HOLE_" not in query_sexpr:
                tree = parse_sexpr(query_sexpr)
                result = evaluate_in_kb(tree, kb)
                if result is not None:
                    q_result = str(result)

            # Inject <q_out> result </q_out> — NOT model-generated
            result_tokens = ["<q_out>"]
            if q_result:
                try:
                    float(q_result)
                    result_tokens.extend(tokenizer.tokenize_number(q_result))
                except ValueError:
                    if q_result in tokenizer.token_to_id:
                        result_tokens.append(q_result)
            result_tokens.append("</q_out>")

            result_ids = [tokenizer.token_to_id[t] for t in result_tokens
                          if t in tokenizer.token_to_id]
            for rid in result_ids:
                gen_ids.append(rid)
                gen_mask.append(False)  # injected, not model-generated
            ids = mx.concatenate([ids, mx.array([result_ids], dtype=mx.int32)], axis=1)
            max_queries -= 1

    return gen_ids, gen_mask, log_probs, used_query


def collect_trajectory(
    model: MultiScaleFFNLM,
    tokenizer: SexprTokenizer,
    kb: dict,
    task: dict,
    temperature: float = 0.7,
    max_steps: int = 5,
) -> Trajectory:
    """Run one sampled iterative refinement trajectory, collecting log-probs."""
    expr_str = extract_expr(task["completion"])
    q_type, entities = extract_question_context(task["prompt"], expr_str)
    expected = task["answer"]

    current_expr = "_HOLE_"
    traj = Trajectory(task_idx=0, correct=False, num_steps=0, reward=0.0)

    for step in range(max_steps):
        # Determine feedback
        if current_expr == "_HOLE_" or "_HOLE_" in current_expr:
            feedback_type = "INCOMPLETE"
            feedback_value = ""
        else:
            tree = parse_sexpr(current_expr)
            result = evaluate_in_kb(tree, kb)
            if result is None:
                feedback_type = "ERROR"
                feedback_value = ""
            elif str(result) == str(expected):
                traj.correct = True
                traj.num_steps = step
                traj.reward = compute_reward(True, step)
                return traj
            else:
                feedback_type = "WRONG"
                feedback_value = str(result)

        # Build input
        input_ids = build_input(tokenizer, current_expr, feedback_type,
                                feedback_value, q_type, entities)
        context_ids = input_ids.tolist()

        # Generate with sampling + log-prob collection
        gen_ids, gen_mask, log_probs, used_q = generate_with_log_probs(
            model, input_ids, tokenizer, kb, temperature=temperature)

        if used_q:
            traj.used_query = True

        traj.steps.append(StepData(
            context_ids=context_ids,
            gen_ids=gen_ids,
            gen_mask=gen_mask,
            old_log_probs=log_probs,
        ))

        # Extract edit
        gen_tokens = tokenizer.decode(gen_ids)
        if "NO_OP" in gen_tokens:
            if current_expr != "_HOLE_" and "_HOLE_" not in current_expr:
                tree = parse_sexpr(current_expr)
                result = evaluate_in_kb(tree, kb)
                traj.correct = result is not None and str(result) == str(expected)
            traj.num_steps = step + 1
            traj.reward = compute_reward(traj.correct, traj.num_steps)
            return traj

        new_expr = extract_edit_from_gen(gen_ids, tokenizer)
        if new_expr and new_expr != current_expr:
            current_expr = new_expr

    # Final check
    if current_expr != "_HOLE_" and "_HOLE_" not in current_expr:
        tree = parse_sexpr(current_expr)
        result = evaluate_in_kb(tree, kb)
        traj.correct = result is not None and str(result) == str(expected)

    traj.num_steps = max_steps
    traj.reward = compute_reward(traj.correct, max_steps)
    return traj


def compute_reward(correct: bool, num_steps: int) -> float:
    if not correct:
        return 0.0
    return 1.0 - 0.05 * max(0, num_steps - 1)


# ============================================================================
# Log-prob computation
# ============================================================================

def compute_step_log_probs(
    model: MultiScaleFFNLM,
    step: StepData,
) -> mx.array:
    """Recompute log-probs for model-generated tokens in a step.

    Single forward pass on [context + gen], extract log-probs at gen positions.
    Returns log-probs only for tokens where gen_mask is True.
    """
    full_ids = step.context_ids + step.gen_ids
    input_ids = mx.array([full_ids[:-1]], dtype=mx.int32)  # shift right

    x = model(input_ids)  # (1, seq_len, dim)
    logits = x @ model.tok_emb.weight.astype(x.dtype).T
    logits = model.softcap(logits).astype(mx.float32)
    log_probs_all = logits - mx.logsumexp(logits, axis=-1, keepdims=True)  # (1, seq_len, vocab)

    # Extract log-probs at generation positions
    ctx_len = len(step.context_ids)
    result = []
    lp_idx = 0
    for i, (gid, is_model) in enumerate(zip(step.gen_ids, step.gen_mask)):
        if is_model:
            pos = ctx_len + i - 1  # position in input that predicts this token
            lp = log_probs_all[0, pos, gid]
            result.append(lp)

    if not result:
        return mx.array([], dtype=mx.float32)
    return mx.stack(result)


# ============================================================================
# GRPO loss
# ============================================================================

def grpo_loss(
    model: MultiScaleFFNLM,
    ref_model: MultiScaleFFNLM,
    trajectories: list[Trajectory],
    advantages: list[float],
    clip_eps: float = 0.2,
    kl_coef: float = 0.05,
) -> mx.array:
    """Compute GRPO loss over a batch of trajectories.

    For each trajectory's model-generated tokens:
      ratio = exp(new_log_prob - old_log_prob)
      clipped_ratio = clip(ratio, 1-eps, 1+eps)
      pg_loss = -min(ratio * A, clipped_ratio * A)
      kl_penalty = kl_coef * (new_log_prob - ref_log_prob)
    """
    total_loss = mx.array(0.0)
    total_tokens = 0

    for traj, advantage in zip(trajectories, advantages):
        if abs(advantage) < 1e-8:
            continue  # skip zero-advantage trajectories

        for step in traj.steps:
            model_gen_count = sum(step.gen_mask)
            if model_gen_count == 0:
                continue

            # Recompute log-probs under current policy
            new_lp = compute_step_log_probs(model, step)
            ref_lp = compute_step_log_probs(ref_model, step)
            old_lp = mx.array(step.old_log_probs, dtype=mx.float32)

            if new_lp.size == 0:
                continue

            # PPO clipped objective
            ratio = mx.exp(new_lp - old_lp)
            adv = mx.array(advantage, dtype=mx.float32)
            surr1 = ratio * adv
            surr2 = mx.clip(ratio, 1.0 - clip_eps, 1.0 + clip_eps) * adv
            pg_loss = -mx.minimum(surr1, surr2)

            # KL penalty against reference
            kl = new_lp - ref_lp
            step_loss = mx.sum(pg_loss + kl_coef * kl)

            total_loss = total_loss + step_loss
            total_tokens += int(new_lp.size)

    if total_tokens == 0:
        return mx.array(0.0)
    return total_loss / total_tokens


# ============================================================================
# Evaluation
# ============================================================================

def quick_eval(
    model: MultiScaleFFNLM,
    tokenizer: SexprTokenizer,
    kb: dict,
    eval_tasks: list[dict],
    max_steps: int = 5,
    use_queries: bool = True,
) -> dict:
    """Quick eval on a subset, returns accuracy by depth."""
    results = defaultdict(lambda: {"ok": 0, "total": 0, "queries": 0})

    for task in eval_tasks:
        depth = task["depth"]
        answer = task["answer"]
        expr_str = extract_expr(task["completion"])
        q_type, entities = extract_question_context(task["prompt"], expr_str)

        if use_queries:
            # Use greedy generation with queries
            from neural_selph.iterative.eval_mlx import generate_with_queries as gen_q
            _, _, ok = iterative_refine(
                model, tokenizer, answer, kb, q_type, entities,
                max_steps=max_steps, use_queries=True)
        else:
            _, _, ok = iterative_refine(
                model, tokenizer, answer, kb, q_type, entities,
                max_steps=max_steps, use_queries=False)

        results[depth]["total"] += 1
        if ok:
            results[depth]["ok"] += 1

    return dict(results)


